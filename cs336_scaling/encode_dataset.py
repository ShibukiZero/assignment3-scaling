from __future__ import annotations

import argparse

from cs336_scaling.tokenization import add_shared_corpus_args, encode_corpus_to_binary


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Encode a text corpus into flat token-id binaries.")
    add_shared_corpus_args(parser)
    parser.add_argument(
        "--tokenizer",
        required=True,
        help="Path to tokenizer.json generated by cs336_scaling.train_tokenizer.",
    )
    parser.add_argument(
        "--output-prefix",
        required=True,
        help="Output prefix for .bin / .idx / .meta.json files.",
    )
    parser.add_argument(
        "--append-eod",
        action="store_true",
        help="Append the configured EOD token after every document.",
    )
    parser.add_argument(
        "--eod-token",
        default="<|endoftext|>",
        help="Special token to append after each document when --append-eod is set.",
    )
    parser.add_argument(
        "--encode-batch-size",
        type=int,
        default=256,
        help="Number of documents to pass to tokenizer.encode_batch at once.",
    )
    return parser


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()

    stats = encode_corpus_to_binary(
        args.input,
        args.tokenizer,
        args.output_prefix,
        text_key=args.text_key,
        parquet_batch_size=args.parquet_batch_size,
        append_eod=args.append_eod,
        eod_token=args.eod_token,
        batch_size=args.encode_batch_size,
    )

    print("Corpus encoding finished.")
    print(f"Documents: {stats.num_documents}")
    print(f"Tokens: {stats.num_tokens}")
    print(f"Files: {stats.num_files}")
    print(f"Output prefix: {args.output_prefix}")


if __name__ == "__main__":
    main()
